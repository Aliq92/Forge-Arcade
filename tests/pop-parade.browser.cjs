const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const url = process.env.ARCADE_TEST_URL || 'http://127.0.0.1:8420';
const output = '/tmp/pop-parade-integration';
(async()=>{
  const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
  try {
    fs.mkdirSync(output,{recursive:true});
    const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.route('https://hits.sh/**',route=>route.abort());
    await page.route('**/games/pop-parade/game.js',async route=>{const response=await route.fetch();await route.fulfill({response,body:await response.text()+'\nexport {game};'});});
    await page.goto(url);await page.waitForTimeout(300);
    const count=await page.locator('#grid [data-game]').count();
    assert.equal(await page.locator('#grid [data-game="pop-parade"]').count(),1);
    assert.equal(await page.locator('#featured-grid [data-game="pop-parade"]').count(),1);
    assert.equal(await page.locator('#footer-count').textContent(),String(count));
    assert.equal(await page.locator('#spotlight [data-game]').getAttribute('data-game'),'digital-ant-colony');
    assert.equal(await page.locator('[data-game="wildform"], [data-game="god-in-a-jar"]').count(),0);
    assert.equal(await page.locator('.arcanum-shortcut').count(),1);
    await page.click('[data-cat="Games"]');
    assert.equal(await page.locator('#grid [data-game="pop-parade"]').count(),1);
    await page.click('[data-cat="Simulations"]');
    assert.equal(await page.locator('#grid [data-game="pop-parade"]').count(),0);
    await page.click('[data-cat="Featured"]');
    assert.equal(await page.locator('#grid [data-game="pop-parade"]').count(),1);
    const card=page.locator('#grid [data-game="pop-parade"]');await card.scrollIntoViewIfNeeded();
    assert.match(await card.locator('.card-art').evaluate(e=>getComputedStyle(e).backgroundImage),/pop-parade-card.svg/);
    await card.screenshot({path:output+'/card.png'});
    await page.evaluate(()=>localStorage.setItem('integration-unrelated','preserve'));
    await card.click();await page.waitForURL('**/games/pop-parade/index.html');
    await page.locator('canvas').focus();await page.keyboard.press('ArrowRight');await page.keyboard.press('Enter');
    await page.waitForTimeout(1500);assert.ok(Number((await page.locator('#score').textContent()).replaceAll(',',''))>0);
    await page.click('#pause');assert.equal(await page.locator('#pause-overlay').isVisible(),true);
    await page.click('#forge-back-link');await page.waitForURL(url+'/index.html');
    assert.equal(await page.locator('#grid [data-game]').count(),count);
    assert.equal(await page.evaluate(()=>localStorage.getItem('integration-unrelated')),'preserve');
    await page.goBack();await page.waitForURL('**/games/pop-parade/index.html');assert.equal(await page.locator('#forge-back-link').count(),1);
    await page.setViewportSize({width:390,height:844});await page.reload();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    const link=await page.locator('#forge-back-link').boundingBox();assert.ok(link.height>=44);
    await page.screenshot({path:output+'/mobile-game.png',fullPage:true});
    await page.click('#forge-back-link');await page.waitForURL(url+'/index.html');
    assert.equal(await page.locator('#grid [data-game="pop-parade"]').count(),1);
    const production=await page.request.get(url+'/dist/games/pop-parade/index.html');assert.equal(production.status(),200);
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({status:'passed',catalogCount:count,checks:['All, Games, Featured, and Simulations filters','featured and archive artwork','existing spotlight and retired-game visibility','native launch and actual balloon pop','pause and return to arcade','browser back','unrelated save preserved','390px mobile return link and no overflow','production game path serves HTTP 200','no JavaScript errors'],screenshots:output},null,2));
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
