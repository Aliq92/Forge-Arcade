const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.env.ARCADE_TEST_URL || 'http://127.0.0.1:8420';
const output = process.env.ARCADE_TEST_OUTPUT || '/tmp/night-freight-integration';
(async () => {
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
  const errors = [], checks = [], failures = [];
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    page.on('pageerror', e => errors.push(e.message));
    page.on('response', r => { if (r.url().startsWith(base) && r.status() >= 400) failures.push(r.url()); });
    await page.route('https://hits.sh/**', route => route.abort());
    await page.goto(base + '/index.html');
    const count = await page.locator('#grid [data-game]').count();
    assert.equal(await page.locator('#grid [data-game="night-freight"]').count(), 1);
    assert.equal(await page.locator('#featured-grid [data-game="night-freight"]').count(), 1);
    assert.equal(await page.locator('#footer-count').textContent(), String(count));
    assert.equal(await page.locator('#spotlight [data-game]').getAttribute('data-game'), 'digital-ant-colony');
    checks.push('Unique All and Featured catalog entries; counts and existing spotlight preserved');
    for (const [filter, expected] of [['Games', 1], ['Simulations', 0], ['Experiments', 0], ['Featured', 1], ['All', 1]]) {
      await page.locator(`[data-cat="${filter}"]`).click();
      assert.equal(await page.locator('#grid [data-game="night-freight"]').count(), expected);
    }
    checks.push('All five catalog filters');
    const card = page.locator('#grid [data-game="night-freight"]');
    await card.scrollIntoViewIfNeeded();
    assert.match(await card.locator('.card-art').evaluate(el => getComputedStyle(el).backgroundImage), /night-freight-card.svg/);
    await card.screenshot({ path: output + '/catalog-card.png' });
    await page.evaluate(() => localStorage.setItem('arcade-integration-unrelated', 'preserve-me'));
    await card.click(); await page.waitForURL('**/games/night-freight/index.html');
    assert.equal(await page.locator('#forge-back-link').getAttribute('href'), '../../index.html');
    await page.locator('[data-action=begin]').click();
    await page.keyboard.down('ArrowRight'); await page.waitForTimeout(700); await page.keyboard.up('ArrowRight');
    await page.locator('#magnet').click(); assert.equal(await page.locator('#magnet-label').textContent(), 'ON · seeking steel');
    await page.locator('#pause').click(); assert.equal(await page.locator('[data-action=resume]').isVisible(), true);
    await page.screenshot({ path: output + '/desktop-game.png', fullPage: true });
    await page.locator('[data-action=resume]').click();
    await page.locator('#forge-back-link').click(); await page.waitForURL(base + '/index.html');
    assert.equal(await page.locator('#grid [data-game]').count(), count);
    assert.equal(await page.evaluate(() => localStorage.getItem('arcade-integration-unrelated')), 'preserve-me');
    checks.push('Native launch, real-time keyboard travel, magnet, pause/resume, return, and unrelated save preservation');
    await page.goBack(); await page.waitForURL('**/games/night-freight/index.html');
    await page.setViewportSize({ width: 390, height: 844 }); await page.reload();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.ok((await page.locator('#forge-back-link').boundingBox()).height >= 44);
    await page.locator('[data-action=begin]').click();
    const right = await page.locator('[data-hold=right]').boundingBox();
    await page.mouse.move(right.x + right.width / 2, right.y + right.height / 2); await page.mouse.down(); await page.waitForTimeout(500); await page.mouse.up();
    await page.screenshot({ path: output + '/mobile-game.png', fullPage: true });
    await page.locator('#forge-back-link').click(); await page.waitForURL(base + '/index.html');
    assert.equal(await page.locator('#grid [data-game="night-freight"]').count(), 1);
    checks.push('Browser back, portrait playfield and held buttons, 44px return target, no horizontal overflow');
    await page.goto(base + '/dist/index.html');
    await page.locator('#grid [data-game="night-freight"]').click();
    await page.waitForURL('**/dist/games/night-freight/index.html');
    await page.locator('[data-action=begin]').click();
    assert.equal(await page.locator('#scene').isVisible(), true);
    await page.locator('#forge-back-link').click(); await page.waitForURL(base + '/dist/index.html');
    for (const asset of ['games/night-freight/vendor/matter.min.js', 'games/night-freight/src/app.js', 'night-freight-card.svg']) assert.equal((await page.request.get(base + '/dist/' + asset)).status(), 200);
    assert.equal((await page.request.get(base + '/dist/games/night-freight/package.json')).status(), 404);
    checks.push('Built Arcade launches and returns with working nested asset paths; development files excluded');
    assert.deepEqual(errors, []); assert.deepEqual(failures, []);
    checks.push('No browser exceptions or failed runtime asset requests');
    const result = { status: 'passed', catalogCount: count, checks, screenshots: output };
    fs.writeFileSync(output + '/results.json', JSON.stringify(result, null, 2)); console.log(JSON.stringify(result, null, 2));
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
