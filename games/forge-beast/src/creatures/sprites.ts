export function creatureSprite(species: SpeciesId): string {
  const rows = sprites[species];
  let ink = '',
    highlight = '';
  rows.forEach((row, y) =>
    [...row].forEach((pixel, x) => {
      if (pixel === '1') ink += `M${x} ${y}h1v1h-1z`;
      if (pixel === '2') highlight += `M${x} ${y}h1v1h-1z`;
    })
  );
  return `<svg viewBox="0 0 ${Math.max(...rows.map(r => r.length))} ${rows.length}" class="fb-creature" aria-label="${species}" role="img" shape-rendering="crispEdges"><path fill="#b5cf85" d="${highlight}"/><path fill="#314a29" d="${ink}"/></svg>`;
}
